function useCountUp(target, dur = 900) {
  const [val, setVal] = useState(0); const started = useRef(false);
  useEffect(() => {
    if (started.current) return; started.current = true;
    if (window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches) { setVal(target); return; }
    const t0 = performance.now(); let raf;
    const tick = (t) => { const p = Math.min(1, (t - t0) / dur); setVal(target * (1 - Math.pow(1 - p, 3))); if (p < 1) raf = requestAnimationFrame(tick); else setVal(target); };
    raf = requestAnimationFrame(tick); return () => cancelAnimationFrame(raf);
  }, [target, dur]);
  return Math.round(val);
}
